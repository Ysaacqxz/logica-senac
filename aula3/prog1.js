/*
variável vs constante

variável => usado para memória de um conteúdo que pode sofrer alteração 
constante => usado para memória de um conteúdo que nao pode ser alterado
*/

// exemplo - variaveis

let nome = 'Elias';
console.log ('Meu nome é ' + nome);

// exemplo - constante

const pais = 'Canadá';
console.log ('Moro no ' + pais);

//segunda parte do progama
//operadores aritiméticos +, -, *, /

let num1 = 10;
let num2 = 2;
let soma = num1 + num2;
let sub = num1 - num2;
let mult = num1 * num2;
let div = num1 / num2;

console.log('O valor da subtração é: ' + sub);
console.log('O valor da multiplicação é: ' + mult);
console.log('O valor da divisão é: ' + div);
console.log('O valor da soma é: ' + soma);

